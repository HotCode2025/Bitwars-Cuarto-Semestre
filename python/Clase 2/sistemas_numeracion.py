# Sistema decimal
a = 10
print(f"Decimal: {a}")

# Sistema binario
a = 0b1010
print(f"Binario: {a}")

# Sistema octal
a = 0o12
print(f"Octal: {a}")

# Sistema hexadecimal
a = 0xA
print(f"Hexadecimal: {a}")

# Base decimal
a = int('23', 10)
print(f"Base decimal: {a}")

# Base binario
a = int('1010', 2)
print(f"Base binario: {a}")

# Base octal
a = int('12', 8)
print(f"Base octal: {a}")

# Base hexadecimal
a = int('A', 16)

# Base 5 (0 a 4)
a = int('344', 5)
print(f"Base 5: {a}")

